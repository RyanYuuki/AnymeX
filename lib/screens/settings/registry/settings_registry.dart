  static Map<String, Widget Function()> get categoryRoutes => {
        for (final cat in categories) cat.title: cat.destination,
      };

  static List<SettingItem> get allItems =>
      categories.expand((c) => c.items).toList();

  static IconData? categoryIcon(String categoryTitle) {
    for (final cat in categories) {
      if (cat.title == categoryTitle) return cat.icon;
    }
    return null;
  }

  static Map<String, List<SettingsCategory>> get groupedCategories {
    final map = <String, List<SettingsCategory>>{};
    for (final cat in categories) {
      map.putIfAbsent(cat.groupTitle, () => []).add(cat);
    }
    return map;
  }
